#!/usr/bin/env node
/**
 * Turn a plaintext denylist into the salted-hash list that
 * check-public-safe.mjs ships.
 *
 * The plaintext list names real people, clients and account identifiers that
 * must never appear in this public repo. Committing it would publish exactly
 * what it exists to keep out, so only the hashes are committed and the
 * plaintext stays on the author's machine.
 *
 *   node scripts/hash-denylist.mjs path/to/plain.txt > scripts/denylist.sha256.txt
 *
 * One entry per line in the plaintext file; blank lines and lines starting
 * with # are ignored.
 */
import { createHash } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { SALT, normalize } from './public-safe-lib.mjs';

const file = process.argv[2];
if (!file) {
  console.error('usage: node scripts/hash-denylist.mjs <plaintext-denylist>');
  process.exit(2);
}

const entries = readFileSync(file, 'utf8')
  .split(/\r?\n/)
  .map((l) => l.trim())
  .filter((l) => l && !l.startsWith('#'));

const hashes = new Set();
for (const entry of entries) {
  const words = normalize(entry);
  if (!words.length) continue;
  if (words.length > 3) {
    console.error(`skipped (longer than 3 words, the scanner only checks 1-3): ${entry}`);
    continue;
  }
  hashes.add(createHash('sha256').update(SALT + words.join(' ')).digest('hex'));
}

console.log('# Salted SHA-256 of strings that must not appear in this repo.');
console.log('# Generated by scripts/hash-denylist.mjs. See that file for why.');
for (const h of [...hashes].sort()) console.log(h);
